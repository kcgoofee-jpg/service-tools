//! 对外公开的上游错误文案（移植自 `app/upstream_errors.py`）：只描述失败，不带任何上游响应内容。
//!
//! 上游的 JSON / HTML 可能含账号信息、URL 或回显的凭据，所以按状态码挑本地文案，而不是尝试脱敏。

pub fn upstream_error_message(status: i64) -> String {
    let message = match status {
        400 | 422 => "上游未接受请求参数，请检查输入",
        401 => "上游服务认证失败，请稍后重试",
        402 => "上游服务额度或权限不足，请稍后重试",
        403 => "上游服务拒绝了请求，请稍后重试",
        404 => "上游服务接口或模型不可用，请稍后重试",
        413 => "请求内容过大，请缩小图片或减少输入",
        429 => "上游请求过于频繁，请稍后重试",
        s if s >= 500 => "上游服务暂时不可用，请稍后重试",
        _ => "上游请求失败，请稍后重试",
    };
    format!("{message}（上游状态 {status}）")
}
